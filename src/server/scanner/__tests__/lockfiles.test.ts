import { describe, expect, it } from "vitest";
import { lockfileKind, parseBunLock, parseLockfile, parsePnpmLock, parseYarnLock } from "../lockfiles";

const names = (pkgs: { name: string; version: string; dev: boolean }[]) =>
  pkgs.map((p) => `${p.name}@${p.version}${p.dev ? " (dev)" : ""}`).sort();

describe("pnpm-lock.yaml", () => {
  it("v9: name@version keys, quoted scoped names; snapshots and importers ignored", () => {
    const lock = `lockfileVersion: '9.0'

importers:
  .:
    dependencies:
      axios:
        specifier: ^1.6.0
        version: 1.6.0

packages:

  '@babel/core@7.22.0':
    resolution: {integrity: sha512-abc}
    engines: {node: '>=6.9.0'}

  axios@1.6.0:
    resolution: {integrity: sha512-def}

  next@14.0.0:
    resolution: {integrity: sha512-ghi}

snapshots:

  next@14.0.0(react@18.2.0):
    dependencies:
      react: 18.2.0
`;
    expect(names(parsePnpmLock(lock, "pnpm-lock.yaml"))).toEqual(["@babel/core@7.22.0", "axios@1.6.0", "next@14.0.0"]);
  });

  it("v6: leading slash, peer suffixes and dev flags", () => {
    const lock = `lockfileVersion: '6.0'

packages:

  /axios@1.6.0:
    resolution: {integrity: sha512-a}
    dev: false

  /next@14.0.0(react-dom@18.2.0)(react@18.2.0):
    resolution: {integrity: sha512-b}
    dev: false

  /vitest@1.0.0:
    resolution: {integrity: sha512-c}
    dev: true
`;
    expect(names(parsePnpmLock(lock, "pnpm-lock.yaml"))).toEqual(["axios@1.6.0", "next@14.0.0", "vitest@1.0.0 (dev)"]);
  });

  it("v5: name/version keys with peer hashes", () => {
    const lock = `lockfileVersion: 5.4

packages:

  /@babel/core/7.22.0:
    resolution: {integrity: sha512-a}
    dev: true

  /styled-jsx/5.1.1_react@18.2.0:
    resolution: {integrity: sha512-b}
`;
    expect(names(parsePnpmLock(lock, "pnpm-lock.yaml"))).toEqual(["@babel/core@7.22.0 (dev)", "styled-jsx@5.1.1"]);
  });
});

describe("yarn.lock", () => {
  it("v1: multiple descriptors per entry, scoped packages", () => {
    const lock = `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1


"@babel/core@^7.0.0", "@babel/core@^7.1.0":
  version "7.22.0"
  resolved "https://registry.yarnpkg.com/@babel/core/-/core-7.22.0.tgz#abc"
  integrity sha512-abc

axios@^1.6.0:
  version "1.6.0"
  resolved "https://registry.yarnpkg.com/axios/-/axios-1.6.0.tgz#def"
`;
    expect(names(parseYarnLock(lock, "yarn.lock"))).toEqual(["@babel/core@7.22.0", "axios@1.6.0"]);
  });

  it("Berry: npm: protocol, skips __metadata, workspaces and patches", () => {
    const lock = `__metadata:
  version: 8
  cacheKey: 10

"@babel/core@npm:^7.0.0, @babel/core@npm:^7.1.0":
  version: 7.22.0
  resolution: "@babel/core@npm:7.22.0"

"axios@npm:^1.6.0":
  version: 1.6.0
  resolution: "axios@npm:1.6.0"

"my-app@workspace:.":
  version: 0.0.0-use.local
  resolution: "my-app@workspace:."

"resolve@patch:resolve@npm%3A^1.22.0#~builtin<compat/resolve>":
  version: 1.22.8
  resolution: "resolve@patch:resolve@npm%3A1.22.8#~builtin<compat/resolve>::version=1.22.8&hash=c3c19d"
`;
    expect(names(parseYarnLock(lock, "yarn.lock"))).toEqual(["@babel/core@7.22.0", "axios@1.6.0"]);
  });
});

describe("bun.lock", () => {
  it("reads packages despite trailing commas; skips workspace entries", () => {
    const lock = `{
  "lockfileVersion": 1,
  "workspaces": {
    "": {
      "name": "my-app",
      "dependencies": { "axios": "^1.6.0", },
    },
  },
  "packages": {
    "@supabase/supabase-js": ["@supabase/supabase-js@2.39.0", "", { "dependencies": { "ws": "^8.0.0" } }, "sha512-a"],
    "axios": ["axios@1.6.0", "", {}, "sha512-b,c"],
    "my-lib": ["my-lib@workspace:packages/lib"],
  },
}
`;
    expect(names(parseBunLock(lock, "bun.lock"))).toEqual(["@supabase/supabase-js@2.39.0", "axios@1.6.0"]);
  });
});

describe("parseLockfile", () => {
  it("dispatches by file name and ignores unsupported files", () => {
    expect(lockfileKind("apps/web/pnpm-lock.yaml")).toBe("pnpm");
    expect(lockfileKind("bun.lockb")).toBeNull();
    expect(parseLockfile("README.md", "axios@1.6.0")).toEqual([]);
    expect(parseLockfile("package-lock.json", "{not json")).toEqual([]);
  });
});
